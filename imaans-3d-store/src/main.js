// ---------- loop ----------
const clock = new THREE.Clock();
let frameMsEma = 16.7, running = true;
let booting = true;      // the loader covers the canvas until 'ready': run updaters, draw nothing
let readyAt = 0;         // wall-clock s at 'ready'
// Governor + frame-skip run on wall-clock seconds: ctx.time advances ≤ 0.05 s per frame, so below 20 fps it
// runs slow — exactly when the governor has to react.
const wall = () => performance.now() / 1000;
const minScale = Math.min(1, q.minDpr / baseDpr); // never below q.minDpr
const gov = { next: 0, slow: 0, good: 0, ceiling: 1, lastUp: -1e9, cappedAt: 0 };
const skip = { on: false, since: 0, odd: false, still: 0 };
const _camPrev = new Float64Array(9);
function frame() {
  const raw = clock.getDelta();
  const dt = Math.min(raw, 0.05);
  ctx.time += dt;
  renderer.info.reset();
  // one misbehaving module must never freeze the store (three stops the loop when a callback throws)
  for (let i = 0; i < updaters.length; i++) { try { updaters[i](dt, ctx.time); } catch (e) { reportOnce(e, updaters[i]); } }
  if (booting) return;
  // Light frame-skip: a device that can't reach ~22 fps even at the minimum resolution draws every other
  // frame while the camera is at rest (particles keep animating at half rate; the first move → every frame).
  const still = cameraStill(Math.min(raw, 0.25));
  if (skip.on) {
    if (!still || wall() - skip.since > 4) skip.on = false;
    else if ((skip.odd = !skip.odd)) { perf.frameSkip++; return; }
  } else {
    frameMsEma = frameMsEma * 0.93 + Math.min(raw, 0.1) * 1000 * 0.07; // clamp: one long hitch ≠ a slow device
    if (!shotMode && still && frameMsEma > 45 && dprScale <= minScale + 1e-3 && wall() - readyAt > 4) { skip.on = true; skip.since = wall(); }
  }
  try { ctx.render(); } catch (e) { reportOnce(e, ctx.render); }
  if (!perf.firstFrameMs) perf.firstFrameMs = Math.round(performance.now());
  if (!shotMode) governor();
}
/** True while the camera hasn't moved for 0.6 s (position, rotation, fov/aspect; no allocation). */
function cameraStill(dt) {
  const p = camera.position, r = camera.quaternion, c = _camPrev;
  const moved = p.x !== c[0] || p.y !== c[1] || p.z !== c[2] || r.x !== c[3] || r.y !== c[4] || r.z !== c[5] || r.w !== c[6] || camera.fov !== c[7] || camera.aspect !== c[8];
  if (moved) { c[0] = p.x; c[1] = p.y; c[2] = p.z; c[3] = r.x; c[4] = r.y; c[5] = r.z; c[6] = r.w; c[7] = camera.fov; c[8] = camera.aspect; }
  skip.still = moved ? 0 : skip.still + dt;
  return skip.still > 0.6;
}
/**
 * Dynamic resolution: keep phones smooth without a manual quality menu. Down a step (×0.85, never below
 * q.minDpr) after two slow checks (> 25 ms ≈ < 40 fps) or one very slow one (> 34 ms); back up (×1.08) after
 * three good checks (< 18.5 ms — reachable on a 60 Hz display; the old 15 ms threshold never was, so one
 * hitch lowered the resolution for good). A step up that turns slow within 6 s caps the scale there for 30 s
 * (no ping-pong: every change reallocates the post-processing targets).
 */
function governor() {
  const t = wall();
  if (t < gov.next) return;
  gov.next = t + 1;
  if (gov.ceiling < 1 && t - gov.cappedAt > 30) gov.ceiling = 1;
  const ms = frameMsEma;
  if (ms > 25 && dprScale > minScale + 1e-3) {
    gov.good = 0;
    if (++gov.slow >= 2 || ms > 34) {
      if (t - gov.lastUp < 6) { gov.ceiling = Math.max(minScale, dprScale / 1.08); gov.cappedAt = t; }
      setDprScale(Math.max(minScale, dprScale * 0.85)); gov.slow = 0;
    }
  } else if (ms < 18.5 && dprScale < gov.ceiling - 1e-3) {
    gov.slow = 0;
    if (++gov.good >= 3) { gov.good = 0; gov.lastUp = t; setDprScale(Math.min(gov.ceiling, dprScale * 1.08)); }
  } else { gov.slow = 0; gov.good = 0; }
}
const _reported = new WeakSet();
function reportOnce(e, fn) { if (_reported.has(fn)) return; _reported.add(fn); console.error('[loop]', e); stats.errors.push('loop: ' + (e && e.message)); }
function setDprScale(s) {
  dprScale = s; renderer.setPixelRatio(baseDpr * s);
  renderer.setSize(window.innerWidth, window.innerHeight);
  for (const fn of resizers) fn(window.innerWidth, window.innerHeight);
  perf.dprChanges++;
  gov.next = wall() + 1.5; // let the realloc frame pass before judging the new size
}
let paused = false;      // IMAANS_STORE.pause(): the embedding page stopped the store (e.g. left its route)
let loopStarted = false; // boot has started the loop (before that, resume() must not start it early)
/** Start / stop the render loop from the current state (tab visible, not paused, boot past setup). */
function syncLoop() {
  const on = loopStarted && running && !paused;
  renderer.setAnimationLoop(on ? frame : null);
  clock.getDelta(); // the time spent stopped is never one giant frame
  if (on) { frameMsEma = 16.7; gov.next = wall() + 2; gov.slow = gov.good = 0; skip.on = false; skip.still = 0; }
}
document.addEventListener('visibilitychange', () => {
  running = !document.hidden;
  syncLoop(); // hidden tab: no frames at all
});

// ---------- embedding API (website integration — see INTEGRATION.md §4) ----------
// window.IMAANS_STORE.pause() stops the render loop and with it the governor, frame-skip, updaters and
// particles (nothing runs while paused; the WebGL context and everything built stay alive). resume() restarts
// cleanly: fresh clock (no time jump), governor state reset, a resize catch-up if the window changed meanwhile.
// ctx.events gets 'pause' / 'resume' events. Calling either twice is harmless.
let _pausedSize = '';
window.IMAANS_STORE = {
  ctx,
  pause() {
    if (paused) return;
    paused = true; _pausedSize = window.innerWidth + 'x' + window.innerHeight;
    syncLoop();
    events.dispatchEvent(new CustomEvent('pause'));
  },
  resume() {
    if (!paused) return;
    paused = false;
    if (window.innerWidth + 'x' + window.innerHeight !== _pausedSize) onResize();
    syncLoop();
    events.dispatchEvent(new CustomEvent('resume'));
  },
  isPaused() { return paused; },
};

// ---------- shader warm-up ----------
// Phones compile every program on first sight. Before the loader lifts, compile everything the store can
// show — from every direction — into the render target the main pass really uses, and bake the shadows.
let mainTargets = [];    // render target(s) the main scene pass draws into (null = the screen)
/** Run ctx.render() once with the scene pass skipped, to learn its target(s); post passes compile meanwhile. */
function findMainTargets() {
  const seen = new Set(); const orig = renderer.render;
  renderer.render = function (s, c) { if (s === scene) { seen.add(renderer.getRenderTarget()); return; } return orig.call(this, s, c); };
  try { ctx.render(); } catch (e) { /* the real render reports it */ } finally { renderer.render = orig; }
  return seen.size ? [...seen] : [null];
}
/** compileAsync(object) into each main target, then take every program's first-use queries now. */
async function compileFor(object) {
  const n0 = renderer.info.programs.length, prev = renderer.getRenderTarget();
  for (const rt of mainTargets.length ? mainTargets : [null]) {
    renderer.setRenderTarget(rt);
    // with KHR_parallel_shader_compile the driver links in parallel and we poll; without it compileAsync is just
    // compile() + a timer (and a console warning), so call compile() directly
    try { if (hasParallel() && renderer.compileAsync) await renderer.compileAsync(object, camera, scene); else renderer.compile(object, camera, scene); }
    catch (e) { console.warn('[warm] compile', e && e.message); }
    finally { renderer.setRenderTarget(prev); }
  }
  // Uniform/attribute lookup + link-status query happen on a program's first use: do them behind the loader.
  const progs = renderer.info.programs;
  for (let i = n0; i < progs.length; i++) { try { progs[i].getUniforms(); progs[i].getAttributes(); } catch (e) { /* lost context */ } }
  return renderer.info.programs.length - n0;
}
let _parallel = null;
function hasParallel() { if (_parallel === null) _parallel = renderer.extensions.has('KHR_parallel_shader_compile'); return _parallel; }
async function warmObject(object) {
  if (!mainTargets.length) mainTargets = findMainTargets();
  return compileFor(object);
}
async function warmUp() {
  const t0 = performance.now();
  perf.parallelCompile = hasParallel();
  mainTargets = findMainTargets();
  await compileFor(scene);
  perf.compileMs = Math.round(performance.now() - t0);
  // One real frame with frustum culling off: everything draws once (textures upload, the shadow maps bake with
  // their depth-material variants, post-processing and background programs compile) — all behind the loader.
  const culled = [];
  scene.traverse(o => { if (o.frustumCulled) { o.frustumCulled = false; culled.push(o); } });
  renderer.shadowMap.autoUpdate = false; renderer.shadowMap.needsUpdate = true;
  try { ctx.render(); } catch (e) { console.warn('[warm] render', e && e.message); }
  finally { for (const o of culled) o.frustumCulled = true; }
  renderer.info.reset();
  perf.warmMs = Math.round(performance.now() - t0);
  perf.programsAtReady = renderer.info.programs.length;
}

// ---------- boot ----------
async function boot() {
  const t0 = performance.now();
  const list = MODULES.filter(([name]) => enabled.has(name));
  // Every model the enabled modules need starts downloading now, in parallel (modules still build in order).
  if (PREFETCH) {
    const ids = [...new Set(list.flatMap(([name]) => PREFETCH[name] || []))];
    perf.prefetch = ids.length;
    ctx.assets.prefetch(ids);
  }
  const loaded = await Promise.all(list.map(([name, load]) => load().then(m => [name, m], (e) => {
    console.error('[boot] failed to import', name, e); stats.errors.push(name + ': import ' + e.message); return null;
  })));
  const mods = loaded.filter(Boolean);
  // setup(): early, cheap hooks (e.g. the ui module shows its loader)
  for (const [name, m] of mods) if (m.setup) { try { await m.setup(ctx); } catch (e) { console.error(name, e); stats.errors.push(name + ': setup ' + e.message); } }
  loopStarted = true; syncLoop();   // = setAnimationLoop(frame) unless the tab is hidden or the page paused us
  const wTotal = mods.reduce((a, [name]) => a + (WEIGHT[name] ?? 1), 0) || 1;
  let wDone = 0;
  for (const [name, m] of mods) {
    const ts = performance.now();
    ctx.ui.setLoading(0.86 * wDone / wTotal, name);
    try { if (m.build) await m.build(ctx); }
    catch (e) { console.error('[boot] module failed', name, e); stats.errors.push(name + ': ' + (e && e.message)); }
    stats.modules[name] = { ms: Math.round(performance.now() - ts) };
    wDone += WEIGHT[name] ?? 1;
  }
  // 'ready' phase (textures decode, environment capture, shader warm-up): the loader shows "Opening the doors"
  // at ~90 %; it reaches 100 % when the store is really drawable. Never trap the visitor behind it.
  ctx.ui.setLoading(0.9, 'ready');
  // A ready hook / warm-up that never settles must not leave the visitor on an undrawn canvas either: after
  // 15 s the loader lifts AND drawing starts (a later first-view shader compile beats a store that never opens).
  const safety = setTimeout(() => { ctx.ui.setLoading(1, 'ready'); if (booting) { booting = false; readyAt = wall(); perf.safetyFired = true; } }, 15000);
  const tr = performance.now();
  for (const fn of readyHooks) { try { await fn(ctx); } catch (e) { console.error('[ready]', e); stats.errors.push('ready: ' + e.message); } }
  for (const [name, m] of mods) if (m.ready) { try { await m.ready(ctx); } catch (e) { console.error(name, e); stats.errors.push(name + ': ready ' + e.message); } }
  perf.readyHooksMs = Math.round(performance.now() - tr);
  ctx.ui.setLoading(0.95, 'ready');
  try { await warmUp(); } catch (e) { console.warn('[warm]', e); }
  clearTimeout(safety);
  ctx.ui.setLoading(1, 'ready');
  stats.buildMs = Math.round(performance.now() - t0);
  booting = false; readyAt = wall(); frameMsEma = 16.7; gov.next = readyAt + 3; // governor waits out the loader fade
  events.dispatchEvent(new CustomEvent('ready'));
  if (window.__PREFETCH__ && !PRODUCTION) { // dev/harness: flag models the prefetch scan missed (tools/perf-models.mjs)
    const want = new Set(list.flatMap(([name]) => PREFETCH[name] || []));
    const missed = ctx.assets.requested().filter(id => !want.has(id));
    if (missed.length) console.warn('[assets] loaded without prefetch (add a recognised call shape to tools/perf-models.mjs):', missed.join(', '));
  }
  let n = 0;
  const waitFrames = () => { if (++n > 3) { window.__STORE_READY = true; } else requestAnimationFrame(waitFrames); };
  requestAnimationFrame(waitFrames);
}
// never leave the canvas undrawn: whatever happens in boot, drawing starts when it ends
boot().catch((e) => { console.error('[boot]', e); stats.errors.push('boot: ' + (e && e.message)); }).finally(() => { booting = false; });

