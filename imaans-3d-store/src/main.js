function countLights() { let n = 0, s = 0; scene.traverse(o => { if (o.isLight && o.visible && !o.isAmbientLight) { n++; if (o.castShadow) s++; } }); return { lights: n, shadowCasters: s }; }

/** Per-module draw calls / triangles: renders each module group solo once (into the main pass's target → no extra programs). */
window.__MODSTATS = () => {
  const out = {};
  const vis = Object.fromEntries(Object.entries(groups).map(([k, g]) => [k, g.visible]));
  const prevRT = renderer.getRenderTarget();
  renderer.setRenderTarget(mainTargets[0] || null);
  for (const name of Object.keys(groups)) {
    for (const [k, g] of Object.entries(groups)) g.visible = k === name;
    renderer.info.reset(); renderer.render(scene, camera);
    out[name] = { calls: renderer.info.render.calls, triangles: renderer.info.render.triangles, points: renderer.info.render.points };
  }
  renderer.setRenderTarget(prevRT);
  for (const [k, g] of Object.entries(groups)) g.visible = vis[k];
  return out;
};
